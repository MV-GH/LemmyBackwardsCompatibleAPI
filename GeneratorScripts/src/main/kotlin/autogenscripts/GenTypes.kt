// Requires that dukat is installed https://github.com/Kotlin/dukat
// Rewrites the TS types to Kotlin types
fun downloadTypes(
    version: String,
    subLocation: String,
) {
    val packageName = "$ROOT_PACKAGE${subLocation.replace("/", ".")}.datatypes"
    val tempDir = File("temp").also { it.mkdir() }
    val zipFile = File(tempDir, "lemmy-js.zip")

    runBlocking {
        client.get(getDownloadLink(version))
            .bodyAsChannel()
            .copyAndClose(zipFile.writeChannel())
    }

    // Extract .ts files to datatypes/temp/
    val tsDestDir = File(getTypesPath(subLocation)).also { it.mkdirs() }
    tsDestDir.listFiles()?.forEach { it.delete() }

    ZipFile(zipFile).use { zip ->
        val tsPath = "lemmy-js-client-$version/src/types/"
        for (entry in zip.entries()) {
            if (!entry.name.startsWith(tsPath) || entry.isDirectory) continue
            val name = entry.name.substring(tsPath.length)
            val nameOnly = name.substringBefore(".")
            if (nameOnly in filesThatShouldNotBeAdded) continue
            File(tsDestDir, name).writeBytes(zip.getInputStream(entry).readAllBytes())
        }
    }
    println("TS files extracted")

    val datatypesDir = File(getTypesPath(subLocation, false))
    datatypesDir.listFiles()?.forEach { if (it.name != "temp") it.deleteRecursively() }

    // Run dukat: reads from temp/*.ts, writes .d.kt files to datatypesDir
    println("Starting Dukat process...")
    val proc = ProcessBuilder("bash", "-ic", "dukat temp/*.ts", "exit")
        .directory(datatypesDir)
        .start()
    println(String(proc.inputStream.readAllBytes()))

    // Process each dukat-generated .d.kt → clean .kt
    datatypesDir.listFiles()!!.forEach { typeFile ->
        when {
            typeFile.name.startsWith("lib") -> typeFile.delete()
            typeFile.isFile && typeFile.name.endsWith(".kt") -> {
                val fileName = typeFile.name.substringBefore(".")
                processDukatFile(typeFile, fileName, packageName, ROOT_PACKAGE)
            }
        }
    }

    writeSealedInterfaces(datatypesDir, packageName)

    tsDestDir.deleteRecursively()
    tempDir.deleteRecursively()
    println("Finished!")
}

