fun getTypesPath(
    version: String,
    temp: Boolean = true,
) = "$ROOT_PATH$ROOT_PACKAGE_PATH$version/datatypes" + if (temp) "/temp" else ""

fun getDownloadLink(tag: String) = "https://github.com/LemmyNet/lemmy-js-client/archive/refs/tags/$tag.zip"

/** Replaces `fieldName: String` with `fieldName: EnumClass` on a single line, adding the import if matched. */
fun String.replaceFieldEnum(
    fieldName: String,
    enumClass: String,
    imports: MutableSet<String>,
    rootPackage: String,
): String {
    val pattern = "$fieldName: String"
    if (!contains(pattern)) return this
    imports.add("import $rootPackage${ENUMS_PACKAGE}$enumClass")
    return replace(pattern, "$fieldName: $enumClass")
}

/**
 * Resolves `dynamic /* ... */` union types (produced by dukat for TypeScript union types)
 * back to the appropriate sealed interface type.
 */
fun resolveDynamicType(line: String): String {
    if ("dynamic" !in line) return line

    val sealedType = when {
        // Post (but not PostView) signals PostOrCommentOrPrivateMessage
        Regex("""\bPost\b(?!View)""").containsMatchIn(line) -> "PostOrCommentOrPrivateMessage"
        // ModlogView only appears in NotificationData, not ResolveObjectView
        "ModlogView" in line -> "NotificationData"
        // CommunityView only appears in ResolveObjectView
        "CommunityView" in line -> "ResolveObjectView"
        else -> return line
    }

    val isOptional = "= null" in line

    return line
        .replace(Regex("""List<dynamic /\*.*?\*/>"""), "List<$sealedType>")
        .replace(Regex("""dynamic /\*.*?\*/"""), "$sealedType${if (isOptional) "?" else ""}")
}

/** Applies all field→enum replacements to a single line. File-specific overrides take priority. */
fun applyEnumReplacements(line: String, fileName: String, imports: MutableSet<String>, rootPackage: String): String {
    val fileOverrides = fileFieldEnumOverrides[fileName] ?: emptyMap()
    val effectiveReplacements = globalFieldEnums + fileOverrides

    return effectiveReplacements.entries.fold(line) { acc, (fieldName, enumClass) ->
        acc.replaceFieldEnum(fieldName, enumClass, imports, rootPackage)
    }
}

/** Transforms a single line from dukat-output syntax to Kotlin data class syntax. */
fun processLine(line: String, fileName: String, imports: MutableSet<String>, rootPackage: String): String {
    var k = line
        .replace("interface ", "internal data class ")
        .replace("typealias ", "internal typealias ")
        .replace(" {", "(")
        .replace("}", ")")

    if (k.contains("?") && !k.contains("=")) k += " = null"
    if (k.contains(":")) k += ","

    k = k.replace(Regex("""\bvar\b"""), "val")
         .replace(Regex("""\bArray\b"""), "List")

    k = if (propsThatShouldBeInt.any { k.contains(it) }) {
        k.replace(Regex("""\bNumber\b"""), "Int")
    } else {
        k.replace(Regex("""\bNumber\b"""), "Long")
    }

    if ("my_vote" in k) {
        k = k.replace(Regex("""\bmy_vote: Int\? = null\b"""), "my_vote: Int = 0")
    }

    k = resolveDynamicType(k)
    k = applyEnumReplacements(k, fileName, imports, rootPackage)

    return k
}

/**
 * Adds @SerialName annotation and sealed interface implementations to a data class body,
 * if the type is configured in sealedImplementations.
 */
fun addSealedInterfaceImpl(content: String, fileName: String, imports: MutableSet<String>): String {
    val impl = sealedImplementations[fileName] ?: return content

    imports.add("import kotlinx.serialization.SerialName")
    val interfaceList = impl.interfaces.joinToString(", ")

    val withSerialName = content.replace(
        "internal data class $fileName(",
        "@SerialName(\"${impl.serialName}\")\ninternal data class $fileName(",
    )
    // Replace the last `)` (closing of the data class) with `) : InterfaceList`
    val lastParen = withSerialName.lastIndexOf(')')
    return withSerialName.substring(0, lastParen) + ") : $interfaceList" + withSerialName.substring(lastParen + 1)
}

/** Generates a sealed interface .kt file for each entry in sealedInterfaces. */
fun writeSealedInterfaces(datatypesDir: File, packageName: String) {
    for ((name, info) in sealedInterfaces) {
        val serializableImport = if (info.serializable) "\nimport kotlinx.serialization.Serializable" else ""
        val serializableAnnotation = if (info.serializable) "\n@Serializable" else ""

        File(datatypesDir, "$name.kt").writeText(
            """
            package $packageName

            import kotlinx.serialization.ExperimentalSerializationApi$serializableImport
            import kotlinx.serialization.json.JsonClassDiscriminator

            @OptIn(ExperimentalSerializationApi::class)$serializableAnnotation
            @JsonClassDiscriminator("${info.discriminator}")
            internal sealed interface $name
            """.trimIndent() + "\n"
        )
    }
}

/** Processes a single dukat-generated .d.kt file into a clean Kotlin datatype file. */
fun processDukatFile(typeFile: File, fileName: String, packageName: String, rootPackage: String) {
    val originalContent = typeFile.readText()
    val isTypealias = originalContent.contains("typealias")

    val imports = mutableSetOf<String>()
    if (!isTypealias) imports.add("import kotlinx.serialization.Serializable")

    val lines = originalContent
        .lines()
        .drop(16) // Remove dukat-generated header
        .filter { !it.contains("definedExternally") }
        .map { processLine(it, fileName, imports, rootPackage) }

    var body = lines.joinToString("\n")
    if (!isTypealias) body = addSealedInterfaceImpl(body, fileName, imports)

    val outputFile = File(typeFile.parentFile, "$fileName.kt")
    outputFile.writeText(buildString {
        appendLine("package $packageName")
        appendLine()
        imports.sorted().forEach { appendLine(it) }
        if (imports.isNotEmpty()) appendLine()
        if (!isTypealias) appendLine("@Serializable")
        append(body)
        if (!body.endsWith("\n")) appendLine()
    })

    typeFile.delete()
}

